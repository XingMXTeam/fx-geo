-- GEO 闭环系统 · 生产数据库（Supabase / Postgres）
-- 由本地 SQLite schema（db.py，按 v3 定稿 §6.1 简化）翻译而来，表/列/约束一一对应。
-- 差异仅两处（存储类型层）：自增主键用 identity；audits 的 *_json 三列用 jsonb（值与 SQLite 种子逐项一致）。
--
-- 权限模型：
--   面板公开侧只用 anon key 读 —— 下面为每张表开启 RLS 并只给 anon 建 select 策略；
--   写入走 service_role key / 后台脚本 —— service_role 默认 bypass RLS，不需要写策略；
--   任何其它角色（authenticated 等）没有策略 = 默认拒绝。
--
-- 用法：在 Supabase 项目 SQL Editor 里先跑本文件，再跑 seed.sql。

begin;

create table if not exists public.sites (
    id bigint generated by default as identity primary key,
    domain text unique not null,
    name text not null,
    role text,
    north_star text
);

create table if not exists public.prompts (
    id bigint generated by default as identity primary key,
    site_id bigint not null references public.sites(id),
    set_version text not null,
    category text not null,
    seq integer not null,
    text text not null,
    source text not null default 'manual',
    target_url text
);

create table if not exists public.audits (
    id bigint generated by default as identity primary key,
    site_id bigint not null references public.sites(id),
    run_at text,
    score integer,
    score_version integer not null default 1,
    band text,
    breakdown_json jsonb,
    priorities_json jsonb,
    failures_json jsonb,
    source_file text,
    note text
);

create table if not exists public.baseline_snapshots (
    id bigint generated by default as identity primary key,
    site_id bigint not null references public.sites(id),
    snapshot_date text not null,
    engine text not null,
    metric text not null,
    subject text not null,
    value double precision,
    unit text,
    caliber text,
    source text
);

create table if not exists public.hypotheses (
    id bigint generated by default as identity primary key,
    code text unique not null,
    site_id bigint references public.sites(id),
    scope text,
    title text not null,
    status text not null default 'draft',
    layer text not null,
    hypothesis text,
    primary_metric text,
    baseline_value text,
    target text,
    guardrail text,
    threshold text,
    control_group text,
    cost text,
    stop_condition text,
    hygiene_note text,
    created_at text
);

create table if not exists public.findings (
    id bigint generated by default as identity primary key,
    site_id bigint references public.sites(id),
    scope text,
    layer text not null,
    title text not null,
    evidence text,
    detail text,
    severity text default 'normal',
    source text
);

create table if not exists public.source_status (
    id bigint generated by default as identity primary key,
    source text unique not null,
    label text not null,
    status text not null,
    detail text,
    next_step text,
    updated_at text
);

create table if not exists public.rules (
    id bigint generated by default as identity primary key,
    name text not null,
    statement text not null,
    evidence_level text,
    source text
);

create index if not exists idx_prompts_site on public.prompts(site_id);
create index if not exists idx_audits_site on public.audits(site_id);
create index if not exists idx_baselines_site on public.baseline_snapshots(site_id);
create index if not exists idx_hypotheses_site on public.hypotheses(site_id);
create index if not exists idx_hypotheses_status on public.hypotheses(status);
create index if not exists idx_findings_site on public.findings(site_id);
create index if not exists idx_findings_layer on public.findings(layer);

-- RLS：全部表开启；anon 只读（仅 select）；service_role 默认 bypass，无需策略。
alter table public.sites enable row level security;
alter table public.prompts enable row level security;
alter table public.audits enable row level security;
alter table public.baseline_snapshots enable row level security;
alter table public.hypotheses enable row level security;
alter table public.findings enable row level security;
alter table public.source_status enable row level security;
alter table public.rules enable row level security;

drop policy if exists anon_read on public.sites;
create policy anon_read on public.sites for select to anon using (true);
drop policy if exists anon_read on public.prompts;
create policy anon_read on public.prompts for select to anon using (true);
drop policy if exists anon_read on public.audits;
create policy anon_read on public.audits for select to anon using (true);
drop policy if exists anon_read on public.baseline_snapshots;
create policy anon_read on public.baseline_snapshots for select to anon using (true);
drop policy if exists anon_read on public.hypotheses;
create policy anon_read on public.hypotheses for select to anon using (true);
drop policy if exists anon_read on public.findings;
create policy anon_read on public.findings for select to anon using (true);
drop policy if exists anon_read on public.source_status;
create policy anon_read on public.source_status for select to anon using (true);
drop policy if exists anon_read on public.rules;
create policy anon_read on public.rules for select to anon using (true);

commit;

-- =====================================================================
-- P1 增补（2026-11-02，最小闭环）：假设卡状态机字段 + changes + gate_checks
-- 本节为增量 DDL（IF NOT EXISTS 幂等），不修改上方已灌库的主体定义。
-- 对应本地 SQLite 迁移：migrations_p1.py（ensure_p1_schema）。
-- =====================================================================
begin;

alter table public.hypotheses add column if not exists approved_at text;
alter table public.hypotheses add column if not exists running_at text;
alter table public.hypotheses add column if not exists decided_at text;
alter table public.hypotheses add column if not exists decision text;
alter table public.hypotheses add column if not exists decision_note text;
alter table public.hypotheses add column if not exists effect double precision;
alter table public.hypotheses add column if not exists ci_low double precision;
alter table public.hypotheses add column if not exists ci_high double precision;
alter table public.hypotheses add column if not exists window_days integer default 28;
alter table public.hypotheses add column if not exists expires_at text;

create table if not exists public.changes (
    id bigint generated always as identity primary key,
    hypothesis_id bigint references public.hypotheses(id),
    deployed_at text not null,
    commit_sha text,
    urls text,
    change_type text,
    description text,
    gsc_comparison_started integer not null default 0,
    gsc_comparison_note text,
    created_at text
);

create table if not exists public.gate_checks (
    id bigint generated always as identity primary key,
    checked_at text not null,
    gate text not null,
    subject text not null,
    verdict text not null,
    reasons_json text,
    source text
);

alter table public.changes enable row level security;
alter table public.gate_checks enable row level security;
drop policy if exists anon_read on public.changes;
create policy anon_read on public.changes for select to anon using (true);
drop policy if exists anon_read on public.gate_checks;
create policy anon_read on public.gate_checks for select to anon using (true);

-- audits.score_version: 1 = rubric v1（历史行默认），2 = geo-optimizer 4.19 rubric v2。
-- 已有库的 CREATE TABLE 不会改列，这里补列；新库 CREATE 已含该列，本句是空操作。
alter table public.audits add column if not exists score_version integer not null default 1;

commit;
